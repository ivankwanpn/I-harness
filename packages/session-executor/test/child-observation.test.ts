import { afterEach, expect, it, vi } from "vitest"
import { append, createSession, publishTransient } from "@i-harness/core-session"
import { createAgentTable, type ChildAgentEntry } from "@i-harness/subagent"
import { createChildObservation } from "../src/child-observation.ts"

afterEach(() => vi.useRealTimers())
const entry = (sessionId = "child-1"): ChildAgentEntry => ({ path: "root/worker", status: "running", session: createSession(), sessionId, controller: new AbortController(), mailbox: [] })

it("follows Session replacement and stops listening to the old child", () => {
  const table = createAgentTable(), row = entry(), old = row.session, next = createSession()
  table.add(row.path, row)
  const monitor = createChildObservation(table), notify = vi.fn()
  monitor.subscribe(notify)
  table.update(row.path, row, { session: next })
  notify.mockClear()
  append(old, { type: "user/message", text: "old" })
  expect(notify).not.toHaveBeenCalled()
  append(next, { type: "user/message", text: "new" })
  expect(notify).toHaveBeenCalledExactlyOnceWith({ kind: "changed" })
  expect(monitor.liveSession("child-1")).toBe(next)
  monitor.dispose(); notify.mockClear()
  append(next, { type: "user/message", text: "after close" })
  expect(notify).not.toHaveBeenCalled()
  expect(monitor.liveSession("child-1")).toBeUndefined()
})

it("discovers added children and drops removed or replaced entries even when their path is reused", () => {
  const table = createAgentTable(), monitor = createChildObservation(table), notify = vi.fn()
  monitor.subscribe(notify)
  const first = entry(), second = entry("child-2")
  table.add(first.path, first)
  expect(notify).toHaveBeenCalledOnce()
  expect(monitor.liveSession("child-1")).toBe(first.session)
  table.add(second.path, second)
  expect(monitor.liveSession("child-1")).toBeUndefined()
  notify.mockClear()
  append(first.session, { type: "user/message", text: "stale" })
  expect(notify).not.toHaveBeenCalled()
  append(second.session, { type: "user/message", text: "current" })
  expect(notify).toHaveBeenCalledOnce()
  table.remove(second.path)
  expect(monitor.liveSession("child-2")).toBeUndefined()
  notify.mockClear()
  append(second.session, { type: "user/message", text: "removed" })
  expect(notify).not.toHaveBeenCalled()
  monitor.dispose()
})

it("ignores transient chunks, isolates listener errors and closes once without any timer", () => {
  vi.useFakeTimers()
  const table = createAgentTable(), row = entry(); table.add(row.path, row)
  const monitor = createChildObservation(table), notify = vi.fn()
  monitor.subscribe(() => { throw new Error("broken UI") })
  monitor.subscribe(notify)
  publishTransient(row.session, { type: "assistant/chunk", text: "token" })
  expect(notify).not.toHaveBeenCalled()
  expect(() => append(row.session, { type: "user/message", text: "durable" })).not.toThrow()
  expect(notify).toHaveBeenCalledExactlyOnceWith({ kind: "changed" })
  monitor.dispose(); monitor.dispose()
  expect(notify.mock.calls).toEqual([[{ kind: "changed" }], [{ kind: "closed" }]])
  expect(vi.getTimerCount()).toBe(0)
  table.add("root/after", entry("after"))
  expect(monitor.liveSession("after")).toBeUndefined()
  expect(notify).toHaveBeenCalledTimes(2)
})

it("subscribes to table before enumeration and validates exact live identity on reads", () => {
  const table = createAgentTable(), row = entry()
  const original = table.subscribe.bind(table)
  table.subscribe = listener => { const off = original(listener); table.add(row.path, row); return off }
  const monitor = createChildObservation(table), notify = vi.fn()
  monitor.subscribe(notify)
  append(row.session, { type: "user/message", text: "once" })
  expect(notify).toHaveBeenCalledOnce()
  table.entries().set(row.path, entry("replacement"))
  expect(monitor.liveSession("child-1")).toBeUndefined()
  notify.mockClear()
  append(row.session, { type: "user/message", text: "external stale identity" })
  expect(notify).not.toHaveBeenCalled()
  monitor.dispose()
})
